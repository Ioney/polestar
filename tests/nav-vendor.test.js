// Lua: Polestar_Nav's files, the TOC order, as the client loads them.
const NAV_FILES = xmlFiles(path.join(NAV, 'Nav', 'Nav.xml'));
const GOLDSHIRE = '{ x = -9444.062, y = 77.667, z = 57.353 }';
const FARGODEEP = '{ x = -9791.249, y = 164.438, z = 27.373 }'; // the mine's lower mouth
const ROUTE = `
local Path = Polestar_NavEngine
local frames = {}
Path.after = function(fn) frames[#frames + 1] = fn end
local function drain() while #frames > 0 do table.remove(frames, 1)() end end
local got = {}
Path.Find(0, ${GOLDSHIRE}, ${FARGODEEP}, function(points, cost) got.points, got.cost = points, cost end)
Path.FindCost(0, ${GOLDSHIRE}, ${FARGODEEP}, function(cost) got.costOnly = cost end)
Path.FindMany(0, ${GOLDSHIRE}, { ${FARGODEEP}, { x = 0, y = 6000 } }, function(costs) got.many = costs end)
drain()
local len = 0
for i = 2, #got.points do
	local a, b = got.points[i - 1], got.points[i]
	len = len + math.sqrt((a.x - b.x) ^ 2 + (a.y - b.y) ^ 2)
end
local first, last = got.points[1], got.points[#got.points]
emit({
	cost = got.cost, costOnly = got.costOnly, many = got.many, length = len, n = #got.points,
	first = { first.x, first.y }, last = { last.x, last.y }, map = first.map,
	available = { Path.Available(0), Path.Available(1), Path.Available(2991), Path.Available(530) },
	same = PolestarPathData[0] == (ShortestPathForeverPathData or {})[0],
	api = { type(Path.Cancel), type(Path.Busy), type(Path.FindCost), type(Path.FindMany) },
	decoded = stub.decompressed,
})`;

function checkRoute(got) {
	// Shortest Path Forever 1.15.0 costs this walk 511 running yards; the straight line is 358.
	assert.ok(got.cost > 400 && got.cost < 700, `cost ${got.cost}`);
	assert.ok(got.length > 358 && got.length < 700, `drawn length ${got.length}`);
	assert.ok(got.n >= 3, 'the route bends round the hill');
	assert.ok(Math.abs(got.costOnly - got.cost) < 1e-6, 'FindCost gives the same cost');
	assert.ok(Math.abs(got.many[0] - got.cost) < 1e-6 && got.many[1] === false, 'FindMany: the same cost, and false off the map');
	assert.deepEqual(got.first, [-9444.062, 77.667]);
	assert.deepEqual(got.last, [-9791.249, 164.438]);
	assert.equal(got.map, 0);
	assert.deepEqual(got.available, [true, true, true, false]);
	assert.deepEqual(got.api, ['function', 'function', 'function', 'function']);
	assert.ok(got.decoded > 0);
}

