// Shortest Path Forever's own copy of the maps: the same files under its global.
const SPF_COPY = `local spf = {}\n${NAV_FILES.map((f) => `assert(loadfile(${JSON.stringify(f)}))("ShortestPathForever", spf)`).join('\n')}\nShortestPathForeverPathData, PolestarPathData = PolestarPathData, nil`;

test("shared-tables hazard: with Shortest Path Forever installed our engine reads only PolestarPathData, and its engine trimming its tables mid-search does not touch ours", () => {
	const [got] = runAddon({
		stubs: ['stub_encoding.lua'],
		before: SPF_COPY,
		addons: ['Polestar_Nav'],
		script: `
local Path = Polestar_NavEngine
Path.clock = function() return os.clock() * 1000 end
Path.budget = 0.05
local frames = {}
Path.after = function(fn) frames[#frames + 1] = fn end
-- What Shortest Path Forever's engine does to its tables (PathGrid.lua:464, 501, 841, 850): evict, trim, idle, reset.
local function trimTheirs()
	for _, D in pairs(ShortestPathForeverPathData) do
		D.graph, D.grid, D.height, D.floor = {}, {}, {}, {}
	end
end
local got, n = {}, 0
Path.Find(0, ${GOLDSHIRE}, ${FARGODEEP}, function(points, cost) got.points, got.cost = points, cost end)
while #frames > 0 do
	n = n + 1
	table.remove(frames, 1)()
	trimTheirs()
end
local distinct = true
for map, D in pairs(PolestarPathData) do
	if D == ShortestPathForeverPathData[map] then distinct = false end
end
emit({ cost = got.cost, n = got.points and #got.points, frames = n, distinct = distinct, maps = (function() local k = {} for m in pairs(PolestarPathData) do k[#k + 1] = m end table.sort(k) return k end)() })`,
	}).emitted;
	assert.ok(got.cost > 400 && got.cost < 700, `cost ${got.cost}`);
	assert.ok(got.frames > 1, 'the search ran over several frames, with their tables trimmed after each');
	assert.equal(got.distinct, true, 'no map table is shared');
	assert.deepEqual(got.maps, [0, 1, 2991]);
});

test('C2: a search cancelled mid-way never calls back, and the queue empties', () => {
	const [got] = runAddon({
		stubs: ['stub_encoding.lua'],
		addons: ['Polestar_Nav'],
		script: `
local Path = Polestar_NavEngine
Path.clock = function() return os.clock() * 1000 end
Path.budget = 0.05
local frames = {}
Path.after = function(fn) frames[#frames + 1] = fn end
local called, kept = 0, 0
local job = Path.Find(0, ${GOLDSHIRE}, ${FARGODEEP}, function() called = called + 1 end)
local many = Path.FindMany(0, ${GOLDSHIRE}, { ${FARGODEEP} }, function() called = called + 1 end, nil, nil, function() kept = kept + 1 end)
table.remove(frames, 1)()
local started = not job.done
Path.Cancel(job)
Path.Cancel(many)
local n = 0
while #frames > 0 and n < 1000 do n = n + 1; table.remove(frames, 1)() end
Path.Busy() -- clears the frame the last pump spent
emit({ called = called, started = started, cancelled = job.cancelled == true, busy = Path.Busy(), left = #frames })`,
	}).emitted;
	assert.equal(got.started, true, 'cancelled while the search was under way');
	assert.equal(got.called, 0);
	assert.equal(got.cancelled, true);
	assert.equal(got.left, 0);
	assert.equal(got.busy, false);
});

test('C6: Stormwind flight master to the Mage Quarter never doubles back on a level street, and a rooftop endpoint still routes', () => {
	const [got] = runAddon({
		stubs: ['stub_encoding.lua'],
		addons: ['Polestar_Nav'],
		script: `
local Path = Polestar_NavEngine
local pts = Path.FindSync(0, { x = -8840.56, y = 489.7, z = 109.61 }, { x = -9100, y = 1200 })
local reversals = {}
for i = 2, #pts - 1 do
	local a, b, c = pts[i - 1], pts[i], pts[i + 1]
	local level = a.z and c.z and math.abs(a.z - b.z) < 5 and math.abs(c.z - b.z) < 5
	local ux, uy, vx, vy = b.x - a.x, b.y - a.y, c.x - b.x, c.y - b.y
	local lu, lv = math.sqrt(ux * ux + uy * uy), math.sqrt(vx * vx + vy * vy)
	if level and lu > 0 and lv > 0 and (ux * vx + uy * vy) / (lu * lv) < -0.95 then reversals[#reversals + 1] = string.format("%.0f,%.0f", b.x, b.y) end
end
local roof = Path.FindSync(0, { x = -9010, y = 870 }, { x = -8840.56, y = 489.7 })
emit({ n = #pts, reversals = table.concat(reversals, " "), roof = roof ~= nil })`,
	}).emitted;
	assert.ok(got.n >= 2);
	assert.equal(got.reversals, '');
	assert.equal(got.roof, true);
});

